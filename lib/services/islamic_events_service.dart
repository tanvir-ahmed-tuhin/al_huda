  /// Get current Hijri date components
  static Map<String, int> getHijriComponents(DateTime date) {
    int y = date.year;
    int m = date.month;
    int d = date.day;

    if (m < 3) {
      y -= 1;
      m += 12;
    }

    int a = y ~/ 100;
    int b = 2 - a + (a ~/ 4);
    int jd = (365.25 * (y + 4716)).floor() + (30.6001 * (m + 1)).floor() + d + b - 1524;

    int l = jd - 1948440 + 10632;
    int n = ((l - 1) ~/ 10631);
    l = l - 10631 * n + 354;
    int j = ((10985 - l) ~/ 5316) * ((50 * l) ~/ 17719) + (l ~/ 5670) * ((43 * l) ~/ 15238);
    l = l - ((30 - j) ~/ 15) * ((17719 * j) ~/ 50) - (j ~/ 16) * ((15238 * j) ~/ 43) + 29;
    int hijriMonth = (24 * l) ~/ 709;
    int hijriDay = l - (709 * hijriMonth) ~/ 24;
    int hijriYear = 30 * n + j - 30;

    return {
      'year': hijriYear,
      'month': hijriMonth,
      'day': hijriDay,
    };
  }

  /// Calculates upcoming date for a special day
  static UpcomingEventResult calculateNextOccurrence(
    IslamicSpecialDayModel event, {
    DateTime? fromDate,
  }) {
    final now = fromDate ?? DateTime.now();
    final today = DateTime(now.year, now.month, now.day);

    // Handle weekly Jummah (Friday)
    if (event.isWeekly) {
      int daysUntilFriday = (DateTime.friday - now.weekday) % 7;
      if (daysUntilFriday == 0 && now.hour >= 18) {
        // Friday passed evening -> next Friday
        daysUntilFriday = 7;
      }
      final targetDate = today.add(Duration(days: daysUntilFriday));
      final daysRemaining = targetDate.difference(today).inDays;

      return UpcomingEventResult(
        event: event,
        targetDate: targetDate,
        daysRemaining: daysRemaining,
        isToday: daysRemaining == 0,
        isTomorrow: daysRemaining == 1,
        dateDisplay: daysRemaining == 0 ? 'আজ পবিত্র জুমা' : 'আসন্ন শুক্রবার',
      );
    }

    final curHijri = getHijriComponents(today);
    final curHMonth = curHijri['month']!;
    final curHDay = curHijri['day']!;

    // Find difference in Hijri days
    // Special case for Ayyam al-Beed: occurs every month on 13th
    if (event.id == 'ayyam_al_beed') {
      int daysDiff = 13 - curHDay;
      if (daysDiff < 0) {
        daysDiff += 30;
      }
      final target = today.add(Duration(days: daysDiff));
      final daysRemaining = target.difference(today).inDays;
      return UpcomingEventResult(
        event: event,
        targetDate: target,
        daysRemaining: daysRemaining,
        isToday: daysRemaining == 0,
        isTomorrow: daysRemaining == 1,
        dateDisplay: daysRemaining == 0 ? 'আজ শুরু' : '$daysRemaining দিন বাকি',
      );
    }

    // For fixed Hijri events (Month & Day)
    int targetMonth = event.hijriMonth;
    int targetDay = event.hijriDay;

    // Approximate days distance in Hijri calendar
    int curAbsoluteDay = (curHMonth - 1) * 30 + curHDay;
    int targetAbsoluteDay = (targetMonth - 1) * 30 + targetDay;

    int dayDistance = targetAbsoluteDay - curAbsoluteDay;
    if (dayDistance < 0) {
      // It has passed in this Hijri year, next occurrence is next Hijri year (354 days)
      dayDistance += 354;
    }

    // Refine target Gregorian date by iterative matching
    DateTime targetDate = today.add(Duration(days: dayDistance));
    
    // Fine-tune around targetDate within +/- 3 days for exact match with getHijriComponents
    for (int offset = -3; offset <= 3; offset++) {
      final testDate = today.add(Duration(days: dayDistance + offset));
      final hComp = getHijriComponents(testDate);
      if (hComp['month'] == targetMonth && hComp['day'] == targetDay) {
        targetDate = testDate;
        break;
      }
    }

    final daysRemaining = targetDate.difference(today).inDays;

    return UpcomingEventResult(
      event: event,
      targetDate: targetDate,
      daysRemaining: daysRemaining,
      isToday: daysRemaining == 0,
      isTomorrow: daysRemaining == 1,
      dateDisplay: daysRemaining == 0
          ? 'আজ এই বরকতময় দিন!'
          : daysRemaining == 1
              ? 'আগামীকাল'
              : '${PrayerService.toBanglaDigits(daysRemaining.toString())} দিন বাকি',
    );
  }

  /// Get all upcoming events sorted by closest date
  static List<UpcomingEventResult> getAllUpcomingEvents({DateTime? fromDate}) {
    final list = specialDays.map((e) => calculateNextOccurrence(e, fromDate: fromDate)).toList();
    list.sort((a, b) => a.daysRemaining.compareTo(b.daysRemaining));
    return list;
  }

  /// Get closest upcoming major event (e.g. for Home Screen banner)
  static UpcomingEventResult? getNextMajorEvent({DateTime? fromDate}) {
    final events = getAllUpcomingEvents(fromDate: fromDate);
    if (events.isEmpty) return null;
    return events.first;
  }

  /// Find event by ID
  static IslamicSpecialDayModel? getEventById(String id) {
    try {
      return specialDays.firstWhere((e) => e.id == id);
    } catch (_) {
      return null;
    }
  }
