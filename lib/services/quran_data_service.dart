  /// Fetches Ayahs for a given Surah number.
  /// If built-in/cached, returns instantly. Otherwise fetches from AlQuran Cloud API.
  static Future<List<Ayah>> getSurahAyahs(int surahNumber) async {
    if (_surahCache.containsKey(surahNumber)) {
      return _surahCache[surahNumber]!;
    }

    if (_builtInSurahs.containsKey(surahNumber)) {
      _surahCache[surahNumber] = _builtInSurahs[surahNumber]!;
      return _builtInSurahs[surahNumber]!;
    }

    try {
      // Fetch Arabic, Bengali, and English simultaneously
      final url = Uri.parse(
        'https://api.alquran.cloud/v1/surah/$surahNumber/editions/quran-uthmani,bn.bengali,en.sahih',
      );
      final response = await http.get(url).timeout(const Duration(seconds: 10));

      if (response.statusCode == 200) {
        final data = jsonDecode(response.body);
        if (data['code'] == 200 && data['data'] is List) {
          final arabicEdition = data['data'][0]['ayahs'] as List;
          final bengaliEdition = data['data'][1]['ayahs'] as List;
          final englishEdition = data['data'][2]['ayahs'] as List;

          final List<Ayah> ayahs = [];
          for (int i = 0; i < arabicEdition.length; i++) {
            final ar = arabicEdition[i];
            final bn = i < bengaliEdition.length ? bengaliEdition[i] : null;
            final en = i < englishEdition.length ? englishEdition[i] : null;
            final quranAyahNumber = ar['number'] as int;

            ayahs.add(
              Ayah(
                numberInSurah: ar['numberInSurah'] as int,
                numberInQuran: quranAyahNumber,
                surahNumber: surahNumber,
                textArabic: ar['text'] as String,
                translationBangla: bn != null ? bn['text'] as String : '',
                translationEnglish: en != null ? en['text'] as String : '',
                audioUrl: 'https://cdn.islamic.network/quran/audio/128/ar.alafasy/$quranAyahNumber.mp3',
                sajda: ar['sajda'] is bool ? ar['sajda'] as bool : (ar['sajda'] != false),
              ),
            );
          }

          _surahCache[surahNumber] = ayahs;
          return ayahs;
        }
      }
    } catch (e) {
      // Return fallback offline generated preview if network is offline
    }

    // Fallback if network fails
    final summary = surahList.firstWhere((s) => s.number == surahNumber);
    final fallbackList = List.generate(
      summary.numberOfAyahs,
      (index) => Ayah(
        numberInSurah: index + 1,
        numberInQuran: index + 1,
        surahNumber: surahNumber,
        textArabic: "بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ",
        translationBangla: "সূরা ${summary.nameBangla} - আয়াত ${index + 1} (অনলাইনে পূর্ণ আয়াত লোড করতে ইন্টারনেট সংযুক্ত করুন)",
        translationEnglish: "Surah ${summary.nameEnglish} - Verse ${index + 1}",
      ),
    );
    _surahCache[surahNumber] = fallbackList;
    return fallbackList;
  }

